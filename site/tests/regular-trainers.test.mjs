import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {regularIndex,regularResults,regularTrainerById,regularTeam,regularDetail,DIFFICULTIES} from '../src/assets/regular-trainers.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>JSON.parse(readFileSync(path.join(root,'public/data',name+'.json'),'utf8'));
const data=read('regular-trainers'),catalog=read('catalog'),details=read('details'),locations=read('locations');
const model={catalog,locations:locations.locations,byId:new Map(catalog.species.map(p=>[p.id,p]))};
const state={trainerQ:'',trainerArea:'all',trainerLimit:24};
test('treinadores reais foram extraídos do PBS, sem incluir líderes e chefes',()=>{
  assert.equal(data.version,1);
  assert.equal(data.trainers.length,63);
  assert.equal(Object.keys(data.typeChart).length,18);
  assert.equal(new Set(data.trainers.map(t=>t.id)).size,63);
  assert.equal(data.trainers.filter(t=>t.team.length===3).length,62);
  assert.equal(data.trainers.find(t=>t.name==='Nomi (Auto Grind)').team.length,1);
  assert.ok(data.trainers.every(t=>t.name&&t.trainerType&&t.trainerClass&&t.location));
  assert.ok(data.trainers.every(t=>t.team.every(p=>p.species&&Number.isInteger(p.level)&&p.level>=1)));
  assert.ok(!data.trainers.some(t=>t.name==='Marigold'||t.name==='Danny (2v2 Full Power)'));
});
test('busca por nome, classe, Pokémon e localização mais paginação',()=>{
  assert.deepEqual(DIFFICULTIES.map(t=>t.id),['beginner','intermediate','advanced','master']);
  const all=regularResults(model,data,state);
  assert.equal(all.count,63);
  assert.match(all.html,/data-more="trainers"/);
  assert.equal(regularResults(model,data,{...state,trainerQ:'Régine'}).count,1);
  assert.equal(regularResults(model,data,{...state,trainerQ:'BLASTOISE'}).count>=1,true);
  assert.equal(regularResults(model,data,{...state,trainerArea:'Route 1'}).count,5);
  assert.equal(regularResults(model,data,{...state,trainerQ:'***not-an-existing-trainer***'}).count,0);
  const index=regularIndex(model,data,state);
  assert.match(index,/data-search="trainers"/);
  assert.match(index,/data-select="trainerArea"/);
});
test('ficha reutiliza cartões de equipes e preserva informações originais',()=>{
  const trainer=data.trainers.find(t=>t.name==='Régine');
  const found=regularTrainerById(data,trainer.id);
  assert.equal(found,trainer);
  const html=regularDetail(model,data,trainer,'beginner',details,50);
  assert.match(html,/Nível previsto: 35/);
  assert.match(html,/Blastoise/i);
  assert.match(html,/Golpes|Hydro Pump|Hydropump/i);
  assert.match(html,/70%/);
  assert.match(html,/trainerVariant/);
  assert.match(html,/treinadores/i);
});
test('Master recebe 4º Pokémon para cobrir tipos com nível de 90%',()=>{
  const trainer=data.trainers.find(t=>t.name==='Pyotr');
  const before=JSON.stringify(trainer);
  const basic=regularTeam(model,data,trainer,'advanced',details,50);
  const master=regularTeam(model,data,trainer,'master',details,50);
  const again=regularTeam(model,data,trainer,'master',details,50);
  assert.equal(basic.team.length,3);
  assert.equal(basic.level,35);
  assert.equal(master.level,45);
  assert.equal(master.team.length,4);
  assert.equal(master.team.filter(x=>x.preview).length,1);
  assert.equal(new Set(master.team.map(p=>p.species)).size,4);
  assert.deepEqual(master.team,again.team,'mesmo treinador retorna o mesmo reforço');
  assert.equal(JSON.stringify(trainer),before,'manifesto PBS não é alterado');
  const html=regularDetail(model,data,trainer,'master',details,50);
  assert.match(html,/Reforço Master estimado/);
  assert.match(html,/Nível previsto: 45/);
});
test('o treinador automático continua especial em vez de receber uma equipe fictícia',()=>{
  const trainer=data.trainers.find(t=>t.name==='Nomi (Auto Grind)');
  assert.equal(regularTeam(model,data,trainer,'master',details,50).team.length,1);
});
