"""Generate immutable regional rules for the Essentials plugin installer."""
import hashlib
import json

# SHA-256 of the native map audited with scripts/regions/audit.py.
ENDING_HASH = "0a25e6d2faa0c7ccbc716d398626cc9d1cf97140d34175b7888781734c01e235"


def ruby_literal(value):
    if isinstance(value, str):
        # ASCII Ruby string literal with interpolation disabled.
        return json.dumps(value, ensure_ascii=True).replace("#{", r"\#{")
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ",".join(map(ruby_literal, value)) + "].freeze"
    if isinstance(value, dict):
        return "{" + ",".join(ruby_literal(k) + "=>" + ruby_literal(v) for k, v in value.items()) + "}.freeze"
    raise ValueError(f"Unsupported region setting {type(value)}")


def plan(project, game, target):
    registry = json.loads((project / "site/public/data/regions.json").read_text("utf-8-sig"))
    map_path = game / "Data/Map136.rxdata"
    verified = map_path.is_file() and hashlib.sha256(map_path.read_bytes()).hexdigest() == ENDING_HASH
    raw = ("# Generated by the Blue installer.\nmodule BlueRegionData\n"
           f"  REGISTRY = {ruby_literal(registry)}\n"
           f"  DECADES_VERIFIED = {ruby_literal(verified)}\nend\n")
    return {target / "RegionsData.rb": raw.encode("utf-8")}
